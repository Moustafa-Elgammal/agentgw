// Package docgen generates the reference pages under docs/reference from the code, so they
// cannot drift. `make docs-gen` writes them; a test regenerates them in memory and fails when
// a committed file is out of date.
package docgen

import (
	"sort"
	"strings"
)

// Header starts every generated markdown file.
const Header = "<!-- Generated by make docs-gen. Do not edit. -->\n\n"

// Output paths, relative to the repository root.
const (
	ManifestMD   = "docs/reference/manifest.md"
	ManifestJSON = "docs/reference/manifest.schema.json"
	FlagsMD      = "docs/reference/flags.md"
	ErrorsMD     = "docs/reference/errors.md"
	AuditMD      = "docs/reference/audit-events.md"
	StudioMD     = "docs/reference/studio-api.md"
	OpenAPIYAML  = "docs/openapi/studio.yaml" // hand written, never generated
)

// Files returns every generated file, keyed by its path relative to the repository root.
func Files(root string) (map[string][]byte, error) {
	out := map[string][]byte{}
	schema, err := ManifestSchema()
	if err != nil {
		return nil, err
	}
	out[ManifestJSON] = schema
	md, err := manifestDoc()
	if err != nil {
		return nil, err
	}
	out[ManifestMD] = []byte(md)
	fl, err := flagsDoc(root)
	if err != nil {
		return nil, err
	}
	out[FlagsMD] = []byte(fl)
	out[ErrorsMD] = []byte(errorsDoc())
	au, err := auditDoc()
	if err != nil {
		return nil, err
	}
	out[AuditMD] = []byte(au)
	st, err := studioDoc(root)
	if err != nil {
		return nil, err
	}
	out[StudioMD] = []byte(st)
	return out, nil
}

// mdTable renders rows as a markdown table. Pipes inside cells are escaped.
func mdTable(head []string, rows [][]string) string {
	var b strings.Builder
	b.WriteString("| " + strings.Join(head, " | ") + " |\n")
	b.WriteString("|" + strings.Repeat("---|", len(head)) + "\n")
	for _, r := range rows {
		cells := make([]string, len(r))
		for i, c := range r {
			cells[i] = escapeCell(c)
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	return b.String()
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + s + "`"
}

func codes(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = code(s)
	}
	return strings.Join(parts, ", ")
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// escapeCell makes text safe inside a table cell: pipes are escaped everywhere, and angle
// brackets outside code spans, so text like <public-url> does not become an HTML tag.
func escapeCell(c string) string {
	var b strings.Builder
	inCode := false
	for _, r := range strings.ReplaceAll(c, "\n", " ") {
		switch {
		case r == '`':
			inCode = !inCode
			b.WriteRune(r)
		case r == '|':
			b.WriteString(`\|`)
		case (r == '<' || r == '>') && !inCode:
			if r == '<' {
				b.WriteString("&lt;")
			} else {
				b.WriteString("&gt;")
			}
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}
