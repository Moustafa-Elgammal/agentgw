#!/bin/sh
# Regenerates docs/THIRD-PARTY-LICENSES.md from the modules the binaries are built from.
# Run through compose: docker compose run --rm licenses
set -eu
out=docs/THIRD-PARTY-LICENSES.md
{
  echo "# Third-party licenses"
  echo
  echo "Generated by \`make licenses\` (google/go-licenses v1.6.0) from the packages under"
  echo "\`./cmd/...\`, \`./pkg/...\` and \`./examples/...\`. Do not edit by hand."
  echo "Every license here is Apache-2.0, MIT, BSD, ISC or MPL-2.0, which are compatible with"
  echo "this project's Apache-2.0 license. The generator fails the run otherwise."
  echo
  go run github.com/google/go-licenses@v1.6.0 report ./cmd/... ./pkg/... ./examples/... \
    --template scripts/licenses.tpl 2>/dev/null | sort -u | grep -v '^| github.com/Moustafa-Elgammal/agentgw ' | \
    awk 'BEGIN{print "| Module | Version | License |\n|---|---|---|"} !/^\| Module/ && !/^\|---/'
} > "$out.tmp"
if grep -E '^\| ' "$out.tmp" | grep -v -E '^\| (Module|---)' | grep -v -E 'Apache-2.0|MIT|BSD|ISC|MPL-2.0'; then
  echo "licenses: a license outside the allowed set is listed above" >&2
  rm -f "$out.tmp"
  exit 1
fi
mv "$out.tmp" "$out"
echo "wrote $out"
